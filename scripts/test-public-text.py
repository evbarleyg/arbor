"""Holds public-text.py to a table of situations, with GitHub's part made up.

It is the one script here that writes where everybody reads, under a token that may edit anybody's words. So what it must
not do has as many rows as what it must. Every name, id and address in here is made up.

`make lint` runs this. Exit code 1 when a row comes out wrong.
"""

