GOOD, BAD = "1+robin@users.noreply.github.com", "robin@mail.somewhere.org"


class Repository:
    """A small repository whose first commit stands for the first public one, with `origin` beside it."""

    def __init__(self, folder):
        self.path = os.path.join(folder, "work")
        self.origin = os.path.join(folder, "origin.git")
        # Nothing of git's from outside: inside a hook or `git rebase --exec`, GIT_DIR and its kin point at the real repository,
        # and every commit made here would land there.
        outside = {key: value for key, value in os.environ.items() if not key.startswith(("GIT_", "GITHUB_", "PUBLIC_CHECK_"))}
        self.environment = dict(outside, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1", PUBLIC_CHECK_HIGHEST="40")
        os.makedirs(self.path)
        self.git("init", "--quiet", "--initial-branch=main")
        self.write("LICENSE", LICENCE)
        self.write("docs/long.md", "".join(f"line {number}\n" for number in range(40)))
        self.root = self.commit("the first public commit")
        subprocess.run(["git", "init", "--quiet", "--bare", self.origin], check=True, env=self.environment)
        self.git("remote", "add", "origin", self.origin)
        self.git("push", "--quiet", "origin", "main")
        self.git("checkout", "--quiet", "-b", "fix/something")

    def git(self, *arguments, address=GOOD, name="someone"):
        identity = ["-c", f"user.name={name}", "-c", f"user.email={address}"]
        done = subprocess.run(["git", *identity, *arguments], cwd=self.path, env=self.environment, capture_output=True, text=True, check=False)
        if done.returncode != 0:
            raise RuntimeError(f"git {arguments}: {done.stderr}")
        return done.stdout.strip()

    def write(self, name, text, mode="w"):
        path = os.path.join(self.path, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, mode, **({} if "b" in mode else {"encoding": "utf-8"})) as handle:
            handle.write(text)

    def commit(self, message="fix: something", **who):
        self.git("add", "--all")
        self.git("commit", "--quiet", "--allow-empty", "--message", message, **who)
        return self.git("rev-parse", "HEAD")

    def run(self, *arguments, standard_input=""):
        """Exit code, the rules that found something, and the output."""
        saved, saved_input, check.ROOT_COMMIT = dict(os.environ), sys.stdin, self.root
        os.environ.clear()
        os.environ.update(self.environment)
        sys.stdin = io.StringIO(standard_input)
        output = io.StringIO()
        try:
            with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
                code = check.main(list(arguments), cwd=self.path)
        except SystemExit as left:  # it gives its verdict back; one that walks out with it, 0 above all, must not end this test as well
            code = f"it left by sys.exit({left.code})"
        finally:
            os.environ.clear()
            os.environ.update(saved)
            sys.stdin = saved_input
        text = output.getvalue()
        return code, sorted(set(re.findall(r"^✘ .*?: \[(\w+)\]", text, re.MULTILINE))), text

    def verdict(self, *arguments, **more):
        return self.run(*arguments, **more)[:2]


@table.later
def situation(what, expected, prepare, *arguments):
    """Makes a repository, lets `prepare` change it, and notes what the check says."""
    with tempfile.TemporaryDirectory() as folder:
        repository = Repository(folder)
        more = prepare(repository) or {}
        row(what, repository.verdict(*arguments, **more), expected)


