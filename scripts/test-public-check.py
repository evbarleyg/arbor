def check_the_test_itself():
    """Inside a hook or `git rebase --exec`, git's own variables point at the real repository. Nothing made here may land there."""
    with tempfile.TemporaryDirectory() as folder:
        real = os.path.join(folder, "real.git")
        subprocess.run(["git", "init", "--quiet", "--bare", real], check=True, capture_output=True)
        saved = dict(os.environ)
        os.environ.update(GIT_DIR=real, GIT_WORK_TREE=folder, GIT_INDEX_FILE=os.path.join(folder, "index"))
        try:
            repository = Repository(folder)
            repository.write("docs/x.md", "fine\n")
            repository.commit()
            verdict = repository.verdict()
        finally:
            os.environ.clear()
            os.environ.update(saved)
        landed = subprocess.run(["git", "--git-dir", real, "for-each-ref"], capture_output=True, text=True, check=True).stdout
        row("with GIT_DIR set from outside, the repositories made here are still their own", (verdict, landed), ((0, []), ""))


def check_hook():
    """The hook as git runs it: a push that must not happen does not."""
    with tempfile.TemporaryDirectory() as folder:
        repository = Repository(folder)
        # This repository has no scripts/public-check.py, like a branch from before there was one, so the hook falls back on the
        # copy the installer kept. That copy knows the real first commit, so every history made here is foreign to it.
        install = os.path.join(HERE, "git-hooks", "install.sh")
        subprocess.run([install], cwd=repository.path, env=repository.environment, capture_output=True, check=True)
        repository.write("docs/x.md", "fine\n")
        repository.commit()
        done = subprocess.run(["git", "push", "origin", "fix/something"], cwd=repository.path, env=repository.environment,
                              capture_output=True, text=True, check=False)
        there = subprocess.run(["git", "rev-parse", "--verify", "--quiet", "refs/heads/fix/something"], cwd=repository.origin,
                               env=repository.environment, capture_output=True, check=False).returncode == 0
        row("make hooks: git calls the hook, and a refusal stops the push",
            (done.returncode != 0, "does not descend" in done.stdout + done.stderr, there), (True, True, False))
        again = subprocess.run([install], cwd=repository.path, env=repository.environment, capture_output=True, check=False).returncode
        row("make hooks: a second time renews it", again, 0)
        hook = os.path.join(repository.path, ".git", "hooks", "pre-push")
        with open(hook, "w", encoding="utf-8") as handle:
            handle.write("#!/bin/sh\necho mine\n")
        again = subprocess.run([install], cwd=repository.path, env=repository.environment, capture_output=True, check=False).returncode
        with open(hook, encoding="utf-8") as handle:
            row("make hooks: somebody else's hook stays, and it says so", (again, "mine" in handle.read()), (1, True))
        os.remove(hook)
        repository.git("config", "core.hooksPath", "elsewhere")
        again = subprocess.run([install], cwd=repository.path, env=repository.environment, capture_output=True, check=False).returncode
        row("make hooks: where git looks for hooks elsewhere, it says so", (again, os.path.exists(hook)), (1, False))


